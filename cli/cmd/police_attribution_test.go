// Fail-closed: a body the hook cannot read must be refused, not waved through.
func TestCheckAiSignatureFailsClosedOnOpaqueBody(t *testing.T) {
	t.Parallel()

	commands := []string{
		`gh pr create --title "x" --body-file -`,
		`gh pr create --title "x" --body-file /nonexistent/path/pr.md`,
		`gh pr create --title "x" --body-file <(printf 'Made with Cursor')`,
		`gh pr create --title "x" --body-file "$BODY"`,
		`git commit -F -`,
	}

	for _, command := range commands {
		if msg := checkAiSignature(command); msg == "" {
			t.Errorf("opaque body was not blocked: %q", command)
		} else if !strings.Contains(msg, "cannot read") {
			t.Errorf("expected the opaque-body reason for %q, got %q", command, msg)
		}
	}
}

