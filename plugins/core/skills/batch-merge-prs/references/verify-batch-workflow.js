// Batch verification workflow TEMPLATE.
// Copy this inline into a Workflow({script: ...}) call and edit the PRS array.
// Fans out: 1 deep verifier + 2 adversarial refuters per PR + 1 barrier merge-planner.
// READ-ONLY: agents never mutate git, never edit files, never call mcp__mercadolivre__*.
//
// Returns { verdicts, plan }. Read plan.merge_order / close_superseded / fix_then_merge /
// conflicts_expected / park / needs_human in the main loop and act on them (Step 6+).
//
// GOTCHA — when this Workflow runs in the BACKGROUND, the returned { verdicts, plan } is
// wrapped under `.result` in the task output file. Read it with `jq '.result.plan'` /
// `jq '.result.verdicts'` — a plain `jq '.plan'` returns null.

export const meta = {
  name: 'verify-error-fix-batch',
  description: 'Adversarially verify N autogenerated error-fix PRs for an integration branch (read-only)',
  phases: [
    { title: 'Verify', detail: 'deep verifier per PR: diff + @claude review + already-fixed + Rule1/2/physical' },
    { title: 'Refute', detail: '2 adversarial refute lenses per PR (regression + correctness)' },
    { title: 'Dedup', detail: 'cross-PR supersession/conflict + merge-order plan' },
  ],
}

// EDIT THIS: one entry per in-scope PR (exclude operator-parked contract PRs).
// Annotate large removals / mislabeled features so they get extra scrutiny and land LAST.
const PRS = [
  // { pr: 1191, kpg: 'KPG-179', t: 'import ML compressed-xref labels' },
  // { pr: 1179, kpg: 'KPG-5',  t: 'remove legacy filiais (LARGE REMOVAL — scrutinize blast radius)' },
]

const VERDICT_SCHEMA = {
  type: 'object', additionalProperties: false,
  required: ['pr','classification','rule1_afterpay_risk','rule2_shared_path_risk','physical_only_risk','already_fixed_in_homolog','superseded_by','nits','files_touched','blast_radius','claude_review_verdict','reasoning','confidence'],
  properties: {
    pr: { type: 'integer' },
    classification: { type: 'string', enum: ['MERGE_CLEAN','FIX_THEN_MERGE','CLOSE_SUPERSEDED','PARK','NEEDS_HUMAN'] },
    rule1_afterpay_risk: { type: 'boolean' },
    rule2_shared_path_risk: { type: 'boolean' },
    physical_only_risk: { type: 'boolean' },
    already_fixed_in_homolog: { type: 'boolean' },
    superseded_by: { type: ['integer','null'] },
    nits: { type: 'array', items: { type: 'object', additionalProperties: false, required: ['file','issue','suggested_fix','severity'], properties: {
      file: { type: 'string' }, issue: { type: 'string' }, suggested_fix: { type: 'string' }, severity: { type: 'string', enum: ['blocker','should-fix','nice-to-have'] } } } },
    files_touched: { type: 'array', items: { type: 'string' } },
    blast_radius: { type: 'string' },
    claude_review_verdict: { type: 'string' },
    reasoning: { type: 'string' },
    confidence: { type: 'number' },
  },
}

const REFUTE_SCHEMA = {
  type: 'object', additionalProperties: false,
  required: ['pr','lens','refuted','strongest_objection','changes_classification_to'],
  properties: {
    pr: { type: 'integer' },
    lens: { type: 'string' },
    refuted: { type: 'boolean' },
    strongest_objection: { type: 'string' },
    changes_classification_to: { type: ['string','null'], enum: ['MERGE_CLEAN','FIX_THEN_MERGE','CLOSE_SUPERSEDED','PARK','NEEDS_HUMAN',null] },
  },
}

const DEDUP_SCHEMA = {
  type: 'object', additionalProperties: false,
  required: ['merge_order','close_superseded','fix_then_merge','conflicts_expected','park','needs_human','summary'],
  properties: {
    merge_order: { type: 'array', items: { type: 'integer' } },
    close_superseded: { type: 'array', items: { type: 'object', additionalProperties: false, required: ['pr','superseded_by','proof'], properties: { pr: {type:'integer'}, superseded_by: {type:'integer'}, proof: {type:'string'} } } },
    fix_then_merge: { type: 'array', items: { type: 'object', additionalProperties: false, required: ['pr','fixes'], properties: { pr: {type:'integer'}, fixes: { type:'array', items:{type:'string'} } } } },
    conflicts_expected: { type: 'array', items: { type: 'object', additionalProperties: false, required: ['prs','files','resolution_hint'], properties: { prs: {type:'array',items:{type:'integer'}}, files: {type:'array',items:{type:'string'}}, resolution_hint: {type:'string'} } } },
    park: { type: 'array', items: { type: 'integer' } },
    needs_human: { type: 'array', items: { type: 'integer' } },
    summary: { type: 'string' },
  },
}

const GUARDRAILS = `
READ-ONLY HARD RULES — you are a verifier, not an implementer:
- NEVER run any git state mutation (checkout/switch/merge/rebase/commit/branch/reset/stash/push/worktree/clean). ONLY read-only git (log/show/diff/blame).
- NEVER edit/write files. Inspection only.
- NEVER use any mcp__mercadolivre__* tool (it hangs). To pin code, just read the file.
- The current working tree is the live staging branch (production target). Use it to judge "already fixed".

CONTEXT — these PRs are autogenerated 'fix:' PRs from an error->autofix pipeline (each a KPG/BetterStack error). They will be merged onto an integration branch before a single batch PR to the staging branch. Sibling apps: 'afterpay' dispatches orders to 'ev' (this repo); 'ev' serves THOUSANDS of live paying users across 12 sales platforms + 7 carriers.

NON-NEGOTIABLE CHECKS:
- RULE 1 (afterpay contract): does the change touch the afterpay<->ev integration (endpoints, webhooks, payload fields, status transitions, tracking/order flow, postpaid ledger-debit-at-bipado, fiscal gate)? -> rule1_afterpay_risk=true.
- RULE 2 (never break ev): a fix must be an ADDED branch in an existing seam, NEVER an early-return GATE on a shared multi-platform/multi-carrier path (a gated shared path silently killed tracking for 1,666 orders). If the diff adds an early-return or narrows a shared catch/retry/timeout affecting OTHER platforms/carriers -> rule2_shared_path_risk=true.
- PHYSICAL-ONLY: paylog ships physical products only; if the change touches ingestion/order-creation filters and could drop real physical orders or admit digital ones -> physical_only_risk=true.
- BUSINESS FUNDAMENTALS to never silently change: postpaid ledger timing, fiscal/NF-e gates, status transitions (shipped never regress), retry windows that mask genuine failures (retryUntil needs a maxExceptions companion).

ALSO: ALREADY-FIXED (read the changed files at staging HEAD — already present? -> CLOSE_SUPERSEDED). The @claude review already ran on every PR; read its verdict and harvest real nits.
`

const results = await pipeline(
  PRS,
  (item) => agent(
    `Deep-verify PR #${item.pr} (${item.kpg}: ${item.t}) for batch-merge safety.

${GUARDRAILS}

STEPS:
1. gh pr diff ${item.pr}
2. gh pr view ${item.pr} --json title,body,additions,deletions,files
   gh pr view ${item.pr} --json comments --jq '.comments[] | select(.author.login=="claude") | .body'
3. Read every touched file at staging HEAD: already fixed? gates a shared path (Rule 2)? touches the afterpay contract (Rule 1)? physical-only? business fundamentals?
3b. If the repo has a graph (graphify-out/graph.json or .graphify), enumerate the blast radius of every
    changed symbol BEFORE grepping: \`graphify query "who calls <ChangedClass>::<method>"\` and
    \`graphify explain "<ChangedClass>"\` from the repo root. Use it to fill blast_radius and to find the
    shared/multi-platform callers a diff-local read misses. It is a HINT — confirm each caller in real
    source; any caller grep finds that the graph missed means the graph is stale, say so.
4. Classify + harvest concrete nits worth fixing on the integration branch.

Return the structured verdict. Be conservative: when a shared path or the afterpay contract is involved and you cannot prove a pure added-branch, prefer FIX_THEN_MERGE or NEEDS_HUMAN over MERGE_CLEAN.`,
    { label: `verify:#${item.pr}`, phase: 'Verify', schema: VERDICT_SCHEMA }
  ).then(async (verdict) => {
    if (!verdict) return null
    const lenses = [
      { key: 'regression', ask: `Try HARD to REFUTE that PR #${item.pr} is safe to merge. Hunt a regression: does the diff narrow a shared catch/retry/timeout, add an early-return gate, or change behavior for ANY platform/carrier that was not the error's origin? Touch the afterpay contract or shipped-order status transitions? Re-read gh pr diff ${item.pr} and the shared files at staging HEAD. Default refuted=true if you cannot prove a contained added-branch.` },
      { key: 'correctness', ask: `Try HARD to REFUTE that PR #${item.pr} actually FIXES its error correctly. Does it merely mask/swallow the error (retry window without maxExceptions, downgrading an alert that hides a real break)? Change a business fundamental (postpaid ledger timing, fiscal/NF-e gate, physical-only ingestion)? Drop real orders/labels? Re-read gh pr diff ${item.pr}. Default refuted=true if uncertain.` },
    ]
    const refutations = await parallel(lenses.map((l) => () =>
      agent(`${GUARDRAILS}\n\n${l.ask}\n\nStage-1 verdict for context:\n${JSON.stringify(verdict)}`,
        { label: `refute:${l.key}:#${item.pr}`, phase: 'Refute', schema: REFUTE_SCHEMA })
    ))
    return { ...verdict, refutations: refutations.filter(Boolean) }
  })
)

const verdicts = results.filter(Boolean)
log(`Verified ${verdicts.length}/${PRS.length} PRs; building dedup/merge plan`)

phase('Dedup')
const plan = await agent(
  `You are the merge-planner for a batch of autogenerated error-fix PRs going onto an integration branch (NOT staging yet). Below are per-PR verdicts plus 2 adversarial refutations each.

${GUARDRAILS}

Produce a single merge plan:
- merge_order: PRs safe to merge (MERGE_CLEAN, and FIX_THEN_MERGE after nits), ordered to MINIMIZE conflicts. Put large removals/keystones and broad refactors LAST; group same-file PRs adjacently.
- close_superseded: any PR already on staging OR fully superseded by another in this batch (give the superseding PR + concrete proof).
- fix_then_merge: PRs needing nit-fixes first, each with the concrete fix list.
- conflicts_expected: clusters touching the same files (+ files + resolution hint).
- park: PRs to exclude pending human decision (surviving Rule-1/Rule-2 refutation, or NEEDS_HUMAN).
- needs_human: PRs where refutations genuinely conflict.
- summary: 3-6 sentence executive summary.

A PR with a surviving refutation that tightens its class must NOT be in merge_order.

VERDICTS:
${JSON.stringify(verdicts, null, 1)}`,
  { label: 'dedup-merge-planner', phase: 'Dedup', schema: DEDUP_SCHEMA, effort: 'high' }
)

return { verdicts, plan }
