// Backtick evasion: `Made with `Cursor`` renders as a footer but would reduce
// to "Made with " if inline spans were removed wholesale. Backtick CHARACTERS
// are stripped, the text under them is not — otherwise one backtick pair
// disables the whole gate. Fenced blocks stay exempt: that is the sanctioned
// way for a body to document these strings.
func TestCheckAiSignatureResistsBacktickEvasion(t *testing.T) {
	t.Parallel()

	blocked := []string{
		"Made with `Cursor`",
		"`Made with Cursor`",
		"Co-Authored-By: `Claude` <noreply@anthropic.com>",
		"**Made with [Cursor](https://cursor.com)**",
	}
	for _, body := range blocked {
		command := `gh pr create --title "x" --body ` + shellDoubleQuote(body)
		if msg := checkAiSignature(command); msg == "" {
			t.Errorf("backtick/markdown evasion slipped through: %q", body)
		}
	}

	fenced := "## Summary\n\nDocuments the gate:\n\n```\nMade with Cursor\nCo-Authored-By: Claude <noreply@anthropic.com>\n```\n"
	command := `gh pr create --title "x" --body ` + shellDoubleQuote(fenced)
	if msg := checkAiSignature(command); msg != "" {
		t.Errorf("fenced documentation must pass, got %q", msg)
	}
}

